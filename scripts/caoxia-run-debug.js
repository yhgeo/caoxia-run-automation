/**
 * 苍霞乐跑 · 全自动跑步脚本【调试入口】
 * ============================================================================
 *
 * 与 caoxia-run.js **完全同一套流程**（都走 caoxia-lib/flow.js），
 * 唯一差别是打开调试录制：
 *
 *   · 全程录屏    → /sdcard/脚本/diag/rec_00.mp4, rec_01.mp4 …
 *                   （root screenrecord，每段 170s，自动分段）
 *   · 关键步骤截图 → /sdcard/脚本/diag/step_*.png（按流程顺序命名）
 *   · 等待期采样   → /sdcard/脚本/diag/t_<秒数>.png（每 30s 一张）
 *   · 日志另存     → /sdcard/脚本/caoxia-run-debug.log
 *
 * ---------------------------------------------------------------------------
 * 怎么用：
 *   1. 在 AutoX.js 里运行本脚本（或让定时任务临时指向它）
 *   2. 跑完后把 /sdcard/脚本/diag/ 整个目录拉到电脑：
 *        adb pull /sdcard/脚本/diag  ./diag
 *   3. 直接播放 rec_*.mp4；step_*.png 是每步的定格，出问题时对着看最快
 *   4. 配合 /sdcard/脚本/caoxia-run-debug.log 的时间戳定位
 *
 * ⚠️ 录屏需要 root（本机 AutoX 已授权）。
 *    若 root 不可用，会退化成「只有日志」，不会影响主流程。
 * ⚠️ 每段 170s × 4Mbps ≈ 85MB；一次完整跑约 4~5 段（≈ 400MB）。
 *    脚本每次启动会自动清掉上一次的录制产物，不会无限堆积。
 * ---------------------------------------------------------------------------
 *
 * 注意：调试版与生产版**共用同一把单实例锁**，不会互相干扰。
 */

var C = require("./caoxia-lib/config.js");

// ---- 打开调试录制 ----
C.CFG.debug = true;

// ---- 日志与生产版分开，避免混在一起 ----
C.PATH.log = "/sdcard/脚本/caoxia-run-debug.log";

// 锁仍然共用（C.PATH.lock 保持默认）——防止两个实例同时操作跑步

require("./caoxia-lib/flow.js").run();
